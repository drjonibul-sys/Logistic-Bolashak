def defaults() -> dict:
    out = {}
    for g in GROUPS:
        for it in g["items"]:
            out[it["key"]] = it["value"]
    return out


def meta() -> dict:
    out = {}
    for g in GROUPS:
        for it in g["items"]:
            out[it["key"]] = it
    return out


def validate(values: dict):
    """Проверка и приведение типов. Возвращает (очищенный словарь, список ошибок)."""
    m = meta()
    clean, errors = {}, []
    for k, it in m.items():
        raw = values.get(k, it["value"])
        try:
            v = float(raw)
        except (TypeError, ValueError):
            errors.append(f"{it['label']}: не число")
            continue
        if v != v or v in (float("inf"), float("-inf")):
            errors.append(f"{it['label']}: недопустимое значение")
            continue
        if v < it["min"] or v > it["max"]:
            errors.append(f"{it['label']}: допустимо от {it['min']} до {it['max']}")
            continue
        if it.get("int"):
            if abs(v - round(v)) > 1e-9:
                errors.append(f"{it['label']}: нужно целое число")
                continue
            v = int(round(v))
        clean[k] = v
    return clean, errors
