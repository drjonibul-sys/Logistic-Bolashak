"""Черновик графа дорожной сети гор. -402 для имитационной модели (v0.2).
Длины магистрали = ΔПК × 20 м (шаг пикетажа на плане); длины ортов и БДШ — оценки по контурам плана.
Запуск: python3 -I build_graph402.py <каталог_вывода>"""
import sys, os, csv, json
out = sys.argv[1]
STEP = 20.0  # м на один ПК магистрали
# узлы магистрали: id, ПК, x, y, описание
trunk = [
 ('T08', 8.0, 9485, 33820, 'западный край плана, магистраль уходит за пределы плана'),
 ('T12', 12.7, 9574, 33824, 'Камера перегрузки; примыкание Н/с «Север» −402/−376'),
 ('T17', 16.8, 9632, 33778, 'метка «Подэтажный штрек −402/−392 м»'),
 ('T18', 18.4, 9634, 33745, 'С-18; камеры С-2 (14)'),
 ('T20', 20.0, 9640, 33712, 'развилка к Рудоспуску № 1 и камере разгрузки (С-7)'),
 ('T25', 24.8, 9660, 33618, 'Доставочный орт 66 (проект)'),
 ('T28', 28.4, 9683, 33545, 'Доставочный орт 72; Н/с «Центр» −402/−376; ВХВ'),
 ('T31', 31.2, 9697, 33500, 'Доставочный орт 77'),
 ('T34', 33.6, 9710, 33455, 'Доставочный орт 82'),
 ('T35', 35.2, 9722, 33424, 'Камера для бурения дегаз. скважин'),
 ('T39', 38.7, 9697, 33375, 'РС-3 (ответвление)'),
 ('T41', 40.7, 9655, 33363, 'ответвление к Камере ВВ'),
 ('T46', 46.0, 9610, 33462, 'Заезд на п/э −402 со стороны АТУ (на запад, к АТУ)'),
]
def sect(a, b):
    """Сечение по подписям слоя «Сечения АТУ и Подэтажный штрек −402» (м²)."""
    if b <= 12.7 or a >= 44: return '28.57'
    if a >= 37 and b <= 44: return '29.31'
    if a >= 12.7 and b <= 35.2: return '24.9'
    if a == 35.2: return '24.9 -> 29.31 (с ПК≈37)'
    if a == 40.7: return '29.31 -> 28.57 (с ПК≈44)'
    return '?'
edges = []
for (n1, pk1, *_), (n2, pk2, *_) in zip(trunk, trunk[1:]):
    edges.append({'edge': f'{n1}-{n2}', 'from': n1, 'to': n2, 'kind': 'магистраль (подэтажный штрек / АТУ?)',
                  'length_m': round((pk2 - pk1) * STEP, 0), 'basis': 'ΔПК×20 м', 'section_m2': sect(pk1, pk2), 'status': 'пройдена'})
branches = [
 ('T34', 'O82', 'Доставочный орт 82', 125, 'оценка по контуру', '28.57?', 'пройден'),
 ('T31', 'O77', 'Доставочный орт 77', 135, 'оценка по контуру', '28.57?', 'пройден'),
 ('T28', 'O72', 'Доставочный орт 72', 140, 'оценка по контуру', '28.57?', 'пройден'),
 ('T25', 'O66', 'Доставочный орт 66', 104, 'длина оси проекта (103,9 м)', '28.57?', 'проект'),
 ('T28', 'NSC', 'Н/с «Центр» −402/−376 (пройдено до ≈ПК 34,3)', 90, 'оценка по хордам ПК', '28.57', 'частично'),
 ('T12', 'NSN', 'Н/с «Север» −402/−376 (пройдено до ПК 21,1)', 110, 'оценка по хордам ПК', '21', 'частично'),
 ('T20', 'RS1', 'ответвление к Рудоспуску № 1 / камере разгрузки', 45, 'оценка по контуру', '?', 'пройдено'),
 ('T41', 'KVV', 'Камера ВВ', 35, 'оценка по контуру', '29.31', 'пройдена'),
 ('T39', 'RS3', 'РС-3', 15, 'оценка по контуру', '?', 'пройдена'),
]
for a, b, kind, L, basis, S, st in branches:
    edges.append({'edge': f'{a}-{b}', 'from': a, 'to': b, 'kind': kind, 'length_m': L, 'basis': basis, 'section_m2': S, 'status': st})
bdsh = [('O82', 'БДШ 1/6-402', 52, 'пройден'),
        ('O77', 'БДШ 2/2…2/5-402 (4 шт., южные «пальцы»)', 45, 'пройдены'),
        ('O72', 'БДШ 3/2…3/6-402 (5 шт.)', 60, 'проект'), ('O72', 'БДШ 3/1-402', 60, 'проект'),
        ('O66', 'БДШ 4/1…4/4-402 (4 шт.)', 62, 'проект')]
for o, name, L, st in bdsh:
    edges.append({'edge': f'{o}-{name}', 'from': o, 'to': name, 'kind': 'БДШ (забой ST14)', 'length_m': L, 'basis': 'оценка: проект 61,5–61,7 м; пройдены 38–52 м', 'section_m2': '?', 'status': st})
with open(os.path.join(out, 'graph402_draft_edges.csv'), 'w', newline='', encoding='utf-8') as f:
    w = csv.DictWriter(f, fieldnames=list(edges[0].keys())); w.writeheader(); w.writerows(edges)
nodes = [{'id': n, 'PK': pk, 'x': x, 'y': y, 'note': t} for n, pk, x, y, t in trunk]
json.dump({'nodes': nodes, 'edges': edges, 'step_PK_m': STEP}, open(os.path.join(out, 'graph402_draft.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
# плечи магистрали от устьев ортов до заезда на АТУ (ПК-46)
print('Плечи по магистрали до ПК-46:')
for n, pk, *_ in trunk:
    print(f'  {n}: ПК {pk:5.1f}  ->  {(46 - pk) * STEP:6.0f} м')
print('ИТОГО магистраль ПК-8…ПК-46:', (46 - 8) * STEP, 'м')
